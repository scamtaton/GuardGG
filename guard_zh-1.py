def prep(text: str) -> ZView:
    raw = (text or "")[:4500]
    z = ZView(raw=raw)
    if not raw:
        return z
    nfkd = unicodedata.normalize("NFKD", raw)
    z.v0 = nfkd.translate(_PREP0).lower()
    z.plain = nfkd.translate(_PREP1).lower()
    z.cjk = len(_CJK_RE.findall(z.plain))
    z.letters = sum(1 for c in z.plain if c.isalpha())
    tight = _GAP_RE.sub("", z.plain)
    joined = _JOIN_RE.sub(_join_sub, z.plain)
    vs = [z.plain]
    for v in (tight, joined):
        if v not in vs:
            vs.append(v)
    z.tight, z.joined = tight, joined
    z.views = tuple(vs)
    asc = z.plain.translate(_CYR2LAT)
    z.latin = _latin_words(asc)
    toks = z.latin.split()
    leeted = [t.translate(_LEET) if (re.search(r"[a-z]", t) and re.search(r"[0-9@$!]", t)) else t for t in toks]
    z.latin_leet = " ".join(leeted) if leeted != toks else ""
    return z


def has_cjk(text: str) -> bool:
    return bool(_CJK_RE.search(text or ""))


# ───────── «двуписьменные» шаблоны: из упрощённого шаблона делаем такой, что ловит и традиционные знаки ─────────

def dual(pattern: str) -> str:
    """Каждый иероглиф шаблона заменяется на набор «упрощённый + его традиционные формы» (для шаблонов, которые гоняются по
    тексту guard'а, где традиционное письмо не сводится к упрощённому)."""
    out: list = []
    in_cls = False
    i = 0
    while i < len(pattern):
        c = pattern[i]
        if c == "\\" and i + 1 < len(pattern):
            out.append(pattern[i:i + 2])
            i += 2
            continue
        if c == "[" and not in_cls:
            in_cls = True
        elif c == "]" and in_cls:
            in_cls = False
        extra = _S2T.get(c)
        if extra and _CJK_RE.match(c):
            alts = "".join(sorted(extra - {c}))
            out.append(c + alts if in_cls else "[" + c + alts + "]")
        else:
            out.append(c)
        i += 1
    return "".join(out)


