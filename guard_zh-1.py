def _join_sub(m: "re.Match") -> str:
    s = m.group("s")
    return m.group(0).replace(s, "")


def _latin_words(text: str) -> str:
    """Латинские «слова» (пиньинь) через пробел; цепочки одиночных букв «c a o n i m a» склеиваются."""
    t = _URL_RE.sub(" ", text)
    t = _HANDLE_RE.sub(" ", t)
    toks = re.sub(r"[^a-z0-9]+", " ", t).split()
    out: list = []
    run: list = []
    for tok in toks + [""]:
        if len(tok) == 1 and tok.isalpha():
            run.append(tok)
            continue
        if len(run) >= 3:
            out.append("".join(run))
        else:
            out.extend(run)
        run = []
        if tok:
            out.append(tok)
    return " ".join(out)


