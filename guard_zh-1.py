@dataclass
class ZhResult:
    chinese: bool = False                 # текст в основном китайский
    found: dict = field(default_factory=lambda: {"prof": [], "hate": [], "adult": [], "minor": False})
    hits: list = field(default_factory=list)
    signals: list = field(default_factory=list)   # (имя, вес, пояснение) — в Analysis.signals
    contacts: tuple = ()
    has_contact: bool = False
    fp: Any = None                        # (exact, simhash, ntok) по иероглифам
    stems: Any = None                     # основы для самообучения guard
    groups: set = field(default_factory=set)
    spam_raw: float = 0.0
    shielded: bool = False
    notes: list = field(default_factory=list)


def _contacts(z: ZView) -> list:
    out: list = []
    for v in dict.fromkeys((z.plain, z.tight)):
        for prefix, rx in CONTACT_ZH:
            for m in rx.finditer(v):
                tok = prefix + m.group(1).lower()
                if tok not in out:
                    out.append(tok)
    return out[:6]


def _spam(z: ZView, contacts: list) -> tuple:
    """Возвращает (signals, groups). Логика та же, что в analyze_text guard: группы → «предложение + призыв» → семейства признаков."""
    sig: list = []
    hit: dict = {}
    for name, group, w, rx, why in SPAM_ZH:
        if any(rx.search(v) for v in z.views):
            hit[name] = (group, w, why)
    # плотность: одно правило, но в тексте несколько разных слов оттуда (казино: 百家乐 + 视讯 + 投注…) — это уже не случайность
    for name in ("zh_casino", "zh_bonus_dep", "zh_adult_ad", "zh_blackmarket", "zh_acct_sale", "zh_boost", "zh_black_data"):
        if name in hit:
            rx = next(r for n, g, w, r, y in SPAM_ZH if n == name)
            seen = set()
            for v in z.views:
                seen.update(x if isinstance(x, str) else x[0] for x in rx.findall(v))
            extra = 1.0 if len(seen) >= 3 else (0.5 if len(seen) == 2 else 0.0)
            if extra:
                g, w, y = hit[name]
                hit[name] = (g, w + extra, y)
    if "zh_earn_word" in hit and any(g == "job" and n != "zh_earn_word" for n, (g, _, _) in hit.items()):
        hit.pop("zh_earn_word")
    groups_w: dict = {}
    for name, (group, w, why) in hit.items():
        groups_w.setdefault(group, []).append((w, name, why))
    if contacts:
        groups_w.setdefault("cta", []).append((2.0, "zh_contact", "контакт WeChat/QQ/LINE/Telegram в рекламе (кит.)"))
    damp = bool(WARN_RX.search(z.plain)) and not contacts
    factor = WARN_FACTOR if damp else 1.0
    pitch = cta = False
    for group, items in groups_w.items():
        items.sort(reverse=True)
        w = items[0][0] + (0.5 * items[1][0] if len(items) > 1 else 0.0)
        sig.append((items[0][1] if len(items) == 1 else "zh_" + group, round(w * factor, 2),
                    items[0][2] + (f" (+{len(items) - 1})" if len(items) > 1 else "") + (" · похоже на предупреждение/новость" if damp else "")))
        pitch |= group in PITCH_ZH
        cta |= group == "cta"
    if not damp and pitch and cta:
        sig.append(("pitch_cta", 2.0, "предложение + призыв писать/переходить (кит.)"))
    real = bool(groups_w)
    if not damp and real and len(z.plain) >= 12:
        fam = {k for k, rx in FAMILIES_ZH.items() if any(rx.search(v) for v in z.views)}
        overlap = 2.0 if (pitch and cta) else 0.0
        if len(fam) >= 3:
            if 3.0 - overlap > 0:
                sig.append(("families3", 3.0 - overlap, "сразу три приметы: деньги/работа, выгода, призыв (кит.)"))
        elif len(fam) == 2:
            strong = "cta" in fam and bool(fam & {"money", "work", "sale"})
            w2 = (1.5 if strong else 0.8) - overlap
            if w2 > 0:
                sig.append(("families2", w2, "две приметы рекламы подряд (кит.)"))
    return sig, set(groups_w)


def _shield(z: ZView, hits: list) -> tuple:
    """Разговор О слове («что значит 草泥马?», «как переводится 傻逼») — не ругань. Спрятанные обходом слова не защищаем."""
    cand = [h for h in hits if h.cat in ("prof", "hate") and h.via not in _EVASIVE]
    if not cand:
        return hits, False
    strong = bool(META_STRONG.search(z.plain))
    weak = bool(META_WEAK.search(z.plain))
    if not (strong or weak):
        return hits, False
    quoted = " ".join(_QUOTE_RX.findall(z.plain))
    ok = []
    for h in cand:
        bare = h.text.split(" ≈ ")[0]
        in_q = bool(quoted) and bare in quoted
        # без кавычек защищает только явный «учебный» вопрос и только короткое сообщение; «什么意思» одного мало (это и упрёк «ты что имеешь в виду?»)
        bare_q = weak and ('?' in z.plain) and len(z.plain) <= len(bare) + 8     # «草泥马是什么意思？» — слово и вопрос о нём, больше ничего
        if in_q and (strong or weak) or (strong and len(z.plain) <= 120) or bare_q:
            ok.append(h)
    if len(ok) != len(cand):
        return hits, False
    return [h for h in hits if h not in ok], True


# ───────── отпечаток и основы по иероглифам ─────────
_BIT_TR = bytes.maketrans(b"01", b"\x00\x01")


def _clean_for_fp(z: ZView) -> str:
    t = _URL_RE.sub(" u ", z.plain)
    t = _HANDLE_RE.sub(" m ", t)
    for _, rx in CONTACT_ZH:
        t = rx.sub(lambda m: m.group(0).replace(m.group(1), "#id"), t)
    t = re.sub(r"[0-9]+", "#", t)
    return "".join(c for c in t if c == "#" or c.isalnum())


def fingerprint_zh(z: ZView):
    """(exact, simhash64, ntok) — как fingerprint() в guard, но по трёхзнаковым кускам: у китайского нет пробелов, и тексты из
    пяти «слов» guard иначе не сравнивает. ID контактов/цифры заменены заглушками, поэтому «волна» ловится при смене WeChat-ID."""
    s = _clean_for_fp(z)
    if len(s) < 8 or z.cjk < 6:
        return None
    exact = int.from_bytes(hashlib.blake2b(s.encode(), digest_size=8).digest(), "big")
    shingles = [s[i:i + 3] for i in range(max(1, min(len(s), 800) - 2))]
    counts = [0] * 64
    for sh in shingles:
        h = int.from_bytes(hashlib.blake2b(sh.encode(), digest_size=8).digest(), "big")
        for i in range(64):
            counts[i] += (h >> i) & 1
    n = len(shingles)
    sim = 0
    for i in range(64):
        if 2 * counts[i] > n:
            sim |= 1 << i
    return exact, sim, max(5, len(s) // 2)


def stems_zh(z: ZView) -> list:
    s = _clean_for_fp(z)
    return [s[i:i + 2] for i in range(min(max(0, len(s) - 1), 300))]


def analyze(text: str, existing: tuple = ()) -> "ZhResult | None":
    """Полный разбор китайского текста. None — если в тексте нет ни иероглифов, ни пиньинь-подозрений."""
    if not ZH_ON or not text:
        return None
    z = prep(text)
    if not z.cjk and not z.latin:
        return None
    r = ZhResult(chinese=z.cjk >= 2 and z.ratio >= 0.5)
    found, hits = scan_lexicon(z)
    hits, r.shielded = _shield(z, hits)
    if r.shielded:
        r.notes.append("щит: это вопрос о значении слова, а не ругань — не наказываю")
        found = {"prof": [], "hate": [], "adult": found["adult"], "minor": found["minor"]}
        for h in hits:
            if h.cat in ("prof", "hate"):
                found[h.cat].append(h.text)
    r.found, r.hits = found, hits
    if z.cjk:
        contacts = _contacts(z)
        sig, groups = _spam(z, contacts)
        # созвучия «рекламных» фраз (加威信 / 加危信) — только если обычные правила ничего не нашли
        if not groups and z.cjk >= 3:
            for kind, gl, text_ in phonetic_hits(z.views, ("spam",)):
                sig.append(("zh_homophone_cta", 2.0, f"созвучие рекламной фразы {gl}: {text_} (кит.)"))
                groups = {"cta"}
                break
        r.signals, r.groups, r.contacts = sig, groups, tuple(contacts)
        r.has_contact = bool(contacts)
        if "pitch_cta" in existing:
            r.signals = [s for s in r.signals if s[0] != "pitch_cta"]
        for fam in ("families2", "families3"):
            if fam in existing:
                r.signals = [s for s in r.signals if s[0] != fam]
        r.spam_raw = round(sum(w for _, w, _ in r.signals), 2)
        if r.chinese:
            r.fp = fingerprint_zh(z)
            r.stems = stems_zh(z)
    return r


# ═══════════════════════════ подключение к guard ═══════════════════════════
# Ничего в guard.py не переписывается: подменяются имена в его модуле (analyze_text, learn_stems, Engine._analyze и несколько
# регулярок «кукольного театра»). Любая подмена — в try/except: если в guard.py что-то переименуют, китайский слой тихо
# отключит только эту часть и напишет в лог, а сам guard продолжит работать.

_LANG: "dict" = {}                   # (чат, юзер) → [китайских сообщений, остальных] — для сигнала «смена языка»
_LANG_MAX = 6000
_STATE: dict = {"mod": None, "hooks": []}


def _foreign_adjust(a, r: "ZhResult") -> None:
    """Общий сигнал guard «много букв чужого алфавита» (+1.5) слеп: китайская болтовня получала бы штраф сама по себе.
    auto (по умолчанию): оставляю его только если есть контакт/ссылка или признаки рекламы из двух групп; 1 — всегда; 0 — никогда."""
    mode = KEEP_FOREIGN
    if mode in ("1", "true", "yes", "on") or not r.chinese:
        return
    pitchy = {g for g in r.groups if g in PITCH_ZH or g == "cta"}
    has_link = any(getattr(u, "kind", "allowed") != "allowed" for u in (a.urls or []))
    strong = r.has_contact or has_link or len(pitchy) >= 2
    if mode in ("0", "false", "no", "off") or not strong:
        a.signals[:] = [s for s in a.signals if s[0] != "foreign_script"]


def _recount(mod, a) -> None:
    hard_set = getattr(mod, "HARD_SIGNALS", set())
    a.raw = round(sum(w for _, w, _ in a.signals), 2)
    a.hard = round(sum(w for n, w, _ in a.signals if n in hard_set), 2)


def _wrap_analyze(mod) -> bool:
    orig = getattr(mod, "analyze_text", None)
    if orig is None or getattr(orig, "_zh_wrapped", False):
        return orig is not None

    def analyze_text_zh(text, ents=(), cfg=None, fwd="", known_names=()):
        a = orig(text, ents, cfg, fwd, known_names)
        if not ZH_ON:
            return a
        try:
            r = analyze(text, existing=tuple(s[0] for s in a.signals))
            if r is None:
                return a
            for k in ("prof", "hate", "adult"):
                if r.found[k]:
                    a.found[k] = list(dict.fromkeys(list(a.found.get(k, [])) + r.found[k]))
            if r.found["minor"]:
                a.found["minor"] = True
            a.signals.extend(r.signals)
            if r.notes:
                for note in r.notes:
                    a.signals.append(("zh_note", 0.0, note))
            if r.contacts:
                a.contacts = tuple(dict.fromkeys(tuple(a.contacts) + r.contacts))[:8]
            a.has_contact = bool(a.has_contact or r.has_contact)
            if r.fp:
                a.fp = r.fp
            _foreign_adjust(a, r)
            _recount(mod, a)
            a.zh = r
            if ZH_LOG and (r.found["prof"] or r.found["hate"] or r.found["adult"] or r.signals):
                log.info("китайский слой: мат=%s ненависть=%s 18+=%s сигналы=%s", r.found["prof"], r.found["hate"], r.found["adult"],
                         [(n, w) for n, w, _ in r.signals])
        except Exception:
            log.exception("китайский слой: разбор не удался, текст оставлен как разобрал guard")
        return a

    analyze_text_zh._zh_wrapped = True
    analyze_text_zh.__wrapped__ = orig
    mod.analyze_text = analyze_text_zh
    return True


def _wrap_learn_stems(mod) -> bool:
    orig = getattr(mod, "learn_stems", None)
    if orig is None or getattr(orig, "_zh_wrapped", False):
        return orig is not None

    def learn_stems_zh(n):
        stems = orig(n)
        try:
            folded = getattr(n, "folded", "")
            if ZH_ON and _CJK_RE.search(folded):
                z = prep(folded)
                if z.cjk >= 6 and z.ratio >= 0.5:
                    st = stems_zh(z)
                    if st:
                        return st
        except Exception:
            log.exception("китайский слой: основы для самообучения не получились")
        return stems

    learn_stems_zh._zh_wrapped = True
    mod.learn_stems = learn_stems_zh
    return True


def _wrap_engine(mod) -> bool:
    """Сигнал «смена языка»: аккаунт писал не по-китайски, и вдруг — китайская реклама (типичный взломанный/купленный аккаунт).
    Сам по себе билингв сигнала не получает: нужен ещё хотя бы один признак рекламы."""
    eng = getattr(mod, "Engine", None)
    orig = getattr(eng, "_analyze", None) if eng else None
    if orig is None or getattr(orig, "_zh_wrapped", False):
        return orig is not None

    def _analyze_zh(self, msg, *args, **kw):
        a = orig(self, msg, *args, **kw)
        try:
            if ZH_ON:
                _lang_flip(mod, msg, a)
        except Exception:
            log.exception("китайский слой: «смена языка» не посчиталась")
        return a

    _analyze_zh._zh_wrapped = True
    eng._analyze = _analyze_zh
    return True


def _lang_flip(mod, msg, a) -> None:
    text = (getattr(msg, "text", "") or "").strip()
    if len(text) < 3 or getattr(msg, "edited", False):
        return
    key = (getattr(msg, "chat_id", 0), getattr(msg, "user_id", 0))
    r = getattr(a, "zh", None)
    is_zh = bool(r and r.chinese)
    st = _LANG.get(key)
    if st is None:
        if len(_LANG) >= _LANG_MAX:
            for k in list(_LANG)[:_LANG_MAX // 4]:
                _LANG.pop(k, None)
        st = _LANG[key] = [0, 0]
    prior_zh, prior_other = st
    if is_zh:
        st[0] += 1
    elif any(c.isalpha() for c in text):
        st[1] += 1
    if is_zh and not r.shielded and prior_zh == 0 and prior_other >= 3 and r.spam_raw >= 2.0:
        a.signals.append(("zh_lang_flip", 1.5, "обычно пишет не по-китайски, и вдруг китайская реклама (возможен взломанный аккаунт)"))
        _recount(mod, a)


