def _patch_regexes(mod) -> list:
    done: list = []

    def merge_one(name, pats):
        old = getattr(mod, name, None)
        if old is None or not hasattr(old, "pattern"):
            return
        new = "|".join(dual(p) for p in pats)
        setattr(mod, name, re.compile(old.pattern + "|" + new))
        done.append(name)

    def merge_tuple(name, pats):
        old = getattr(mod, name, None)
        if not isinstance(old, tuple):
            return
        setattr(mod, name, old + tuple(re.compile(dual(p)) for p in pats))
        done.append(name)

    for fn, name, pats in ((merge_tuple, "_ASK_RX", _ASK_ZH), (merge_tuple, "_CONFIRM_RX", _CONFIRM_ZH), (merge_tuple, "_BAIT_RX", BAIT_ZH),
                           (merge_one, "_CLAIM_RX", _CLAIM_ZH), (merge_one, "_MONEY_RX", _MONEY_ZH), (merge_one, "_VERIFY_RX", _VERIFY_ZH)):
        try:
            fn(name, pats)
        except Exception:
            log.exception("китайский слой: не удалось дополнить %s", name)
    dm = getattr(mod, "_DM_SIGNALS", None)
    if isinstance(dm, frozenset):
        mod._DM_SIGNALS = dm | _DM_NAMES
        done.append("_DM_SIGNALS")
    return done


def _find_target(mod=None):
    if mod is not None:
        return mod
    for name in ("__main__", "guard"):
        m = sys.modules.get(name)
        if m is not None and hasattr(m, "analyze_text") and hasattr(m, "scan"):
            return m
    return None


def install(mod=None) -> bool:
    """Подключить китайский слой к модулю guard. Безопасно вызывать повторно."""
    reload_env()
    if not ZH_ON:
        log.info("китайский слой выключен (GUARD_ZH=0)")
        return False
    mod = _find_target(mod)
    if mod is None:
        log.warning("китайский слой: не нашёл модуль guard. Поставь «import guard_zh; guard_zh.install()» НИЖЕ определения analyze_text "
                    "(перед «if __name__ == \"__main__\":») или запускай «python guard_zh.py»")
        return False
    if getattr(mod, "_guard_zh_installed", False):
        return True
    hooks: list = []
    for label, fn in (("analyze_text", _wrap_analyze), ("learn_stems", _wrap_learn_stems), ("Engine._analyze", _wrap_engine)):
        try:
            if fn(mod):
                hooks.append(label)
            else:
                log.warning("китайский слой: в guard нет %s — эта часть пропущена", label)
        except Exception:
            log.exception("китайский слой: подмена %s не удалась", label)
    hooks += _patch_regexes(mod)
    mod._guard_zh_installed = True
    _STATE.update(mod=mod, hooks=hooks)
    if "analyze_text" not in hooks:
        log.error("китайский слой: главную подмену (analyze_text) сделать не удалось — китайский не ловится")
        return False
    log.info("китайский слой %s подключён: %s; строгий режим: %s; «чужой алфавит»: %s",
             ZH_VERSION, ", ".join(hooks), "да" if ZH_STRICT else "нет", KEEP_FOREIGN)
    return True


