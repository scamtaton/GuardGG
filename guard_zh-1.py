WARN_RX = _x(r"受害|通报|案件|讲述|记者|民警|女士|先生|警惕|谨防|小心|防骗|防诈|反诈|骗局|诈骗|骗子|被骗|受骗|提醒(?:大家|各位|广大)|注意防范|提高警惕|切勿|千万别|千万不要|不要相信|别相信|别上当|识别|揭秘|曝光|科普|警方|民警|公安|派出所|96110|"
             r"предупрежд|осторожн|мошенн|развод")
WARN_FACTOR = 0.35

# «что это значит?» — разговор О слове, а не ругань: ученики китайского, цитаты, переводы
META_STRONG = re.compile(r"怎么(?:读|念|翻译)|拼音|翻译|是什么梗|骂人的|骂人话|脏话|粗口|屏蔽词|敏感词|俚语|粗俗|网络用语|流行语|黑话|用语|что\s+(?:значит|означает|такое)|как\s+(?:переводится|читается|понять|перевести)|перевод(?:ится|и)?\b|значени[ея]|"
                         r"ругательств|\bмат\b|\bwhat\s+(?:does|is)\b|\bmeans?\b|\bmeaning\b|\btranslat|\bswear|\bcurse\s?word|\bslang\b", re.I)
META_WEAK = re.compile(r"什么意思|啥意思|是什么|是啥|意思是|含义")
_QUOTE_RX = re.compile(r"[“\"「『‘'`«]([^”\"」』’'`»\n]{1,30})[”\"」』’'`»]")


