def phonetic_hits(views, kinds=("prof", "spam")) -> list:
    """Список (тип, пояснение, найденный текст) для созвучий. Буквальные написания не считаем — их ловят обычные правила."""
    out: list = []
    seen: set = set()
    budget = 1800
    for v in views:
        for run in _CJK_RUN.findall(v):
            if budget <= 0:
                return out
            budget -= len(run)
            syl = [_PY.get(c) for c in run]
            n = len(run)
            for target, kind, gl, veto, sets in _PH_COMPILED:
                if kind not in kinds:
                    continue
                k = len(target)
                for i in range(n - k + 1):
                    ok = True
                    for j in range(k):
                        s = syl[i + j]
                        if not s or target[j] not in s or (sets and run[i + j] not in sets[j]):
                            ok = False
                            break
                    if not ok:
                        continue
                    nxt = run[i + k] if i + k < n else ""
                    if veto and nxt and nxt in veto:
                        continue
                    text = run[i:i + k]
                    if (kind, text) not in seen:
                        seen.add((kind, text))
                        out.append((kind, gl, text))
                    break
    return out


