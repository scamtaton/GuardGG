class _Prep(dict):
    """Таблица для str.translate: убирает невидимые/объединяющие знаки, при желании сводит традиционное письмо к упрощённому."""

    def __init__(self, t2s: bool):
        super().__init__()
        for k, v in _EMOJI_SUB.items():
            self[ord(k)] = v
        if t2s:
            for k, v in _T2S.items():
                self[ord(k)] = v

    def __missing__(self, cp: int):
        ch = chr(cp)
        cat = unicodedata.category(ch)
        val = None if (cat in ("Mn", "Me", "Cf") or (cat == "Cc" and ch not in "\n\t") or cp in (0x2028, 0x2029)) else cp
        self[cp] = val
        return val


