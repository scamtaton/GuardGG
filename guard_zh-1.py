def explain(text: str) -> str:
    r = analyze(text)
    if r is None:
        return "в тексте нет ни иероглифов, ни пиньинь-подозрений"
    z = prep(text)
    lines = [f"иероглифов: {z.cjk}, китайский текст: {'да' if r.chinese else 'нет'}"]
    for k, title in (("prof", "мат"), ("hate", "ненависть"), ("adult", "18+")):
        for x in r.found[k]:
            lines.append(f"  {title}: {x}")
    if r.found["minor"]:
        lines.append("  рядом детская тема → «18+ рядом с детьми»")
    for n, w, why in r.signals:
        lines.append(f"  сигнал {n} ({w:+.2f}): {why}")
    if r.contacts:
        lines.append("  контакты: " + ", ".join(r.contacts))
    for note in r.notes:
        lines.append("  " + note)
    if r.fp:
        lines.append(f"  отпечаток: {r.fp[1]:016x}, «слов»: {r.fp[2]}")
    if len(lines) == 1:
        lines.append("  ничего подозрительного")
    lines.append(f"  сумма признаков спама: {r.spam_raw:.2f} (наблюдать от {2.5}, удалить от {4.0}, блок новичку от {8.0})")
    return "\n".join(lines)


def _run_guard(argv: list) -> int:
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import importlib
    g = importlib.import_module("guard")
    install(g)
    ax = getattr(g, "ax_cli", None)
    if ax is not None:
        r = ax(argv)
        if r is not None:
            return int(r)
    if argv and argv[0].startswith("-"):
        return int(g.cli(argv))
    import asyncio
    try:
        asyncio.run(g.main())
    except KeyboardInterrupt:
        pass
    except SystemExit as e:
        if e.code not in (None, 0):
            print(e.code, file=sys.stderr)
            raise
    return 0


def main(argv: list) -> int:
    if argv and argv[0] == "--zh-version":
        print("guard_zh", ZH_VERSION)
        return 0
    if argv and argv[0] == "--zh-check":
        text = " ".join(argv[1:]) or sys.stdin.read()
        print(explain(text))
        return 0
    if argv and argv[0] == "--zh-selftest":
        return selftest(verbose="-v" in argv)
    return _run_guard(argv)


