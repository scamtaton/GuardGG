def _flag(name: str, default: bool) -> bool:
    raw = os.getenv(name)
    if raw is None or raw.strip() == "":
        return default
    return raw.strip().lower() not in ("0", "false", "no", "off", "нет")


ZH_ON = _flag("GUARD_ZH", True)
ZH_STRICT = _flag("GUARD_ZH_STRICT", False)
KEEP_FOREIGN = (os.getenv("GUARD_ZH_KEEP_FOREIGN") or "auto").strip().lower()
XSLURS = _flag("GUARD_ZH_XSLURS", True)
ZH_LOG = _flag("GUARD_ZH_LOG", False)


def reload_env() -> None:
    """Перечитать настройки (guard вызывает load_env() уже после импорта этого файла)."""
    global ZH_ON, ZH_STRICT, KEEP_FOREIGN, XSLURS, ZH_LOG
    ZH_ON = _flag("GUARD_ZH", True)
    ZH_STRICT = _flag("GUARD_ZH_STRICT", False)
    KEEP_FOREIGN = (os.getenv("GUARD_ZH_KEEP_FOREIGN") or "auto").strip().lower()
    XSLURS = _flag("GUARD_ZH_XSLURS", True)
    ZH_LOG = _flag("GUARD_ZH_LOG", False)


