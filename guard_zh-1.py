#!/usr/bin/env python3
# guard_zh 1.0 — китайский модуль для guard (отдельный файл, guard.py он НЕ правит и не копирует).
#
# Что делает: то же, что guard делает для русского, только для китайского текста —
#   • мат и оскорбления (простой и «шифрованный»: пиньинь-аббревиатуры nmsl/wdnmd/cnm, омофоны 草泥马/尼玛/煞笔,
#     разбивка иероглифов, пробелы/точки/эмодзи между знаками, традиционное письмо, кантонский и тайваньский мат);
#   • ненависть (этнические/ЛГБТ-ярлыки, призывы, нацизм, отрицание геноцида);
#   • 18+ и «18+ рядом с детской темой» (отдельно от бытовых слов вроде 操作/体操);
#   • спам и мошенничество на китайском: 刷单/兼职日结, 杀猪盘, 带单老师, 博彩/菠菜, 担保/跑分/承兑/引流 (жаргон
#     китайских чёрных рынков в Telegram), 贷款, продажа аккаунтов/SIM/данных, 办证, наркотики, 约炮/裸聊,
#     WeChat/QQ/LINE/TG-контакты (идут в «сеть контактов» guard), кукольные диалоги «靠谱吗? / 我也提现了»;
#   ЧЕТЫРЕ ФИШКИ, которых нет у обычных ботов:
#   1) «слух» вместо списка — фонетический ловец омофонов (谐音): иероглифы читаются как слоги, и спрятанный мат/реклама находится,
#      даже если такой маски нет ни в одном словаре (草腻玛, 沙壁, 加危信);
#   2) щит «разговор О слове»: «что значит 草泥马?», «как переводится 傻逼», цитаты и учебные объяснения не наказываются
#      (спрятанное обходом слово щитом не прикрывается), а новости/предупреждения про 刷单 не считаются рекламой;
#   3) «смена языка»: аккаунт писал не по-китайски, и вдруг китайская реклама — добавка к подозрению (типичный взломанный аккаунт);
#   4) русские пояснения: что именно сказали и КАК спрятали («傻逼 = долбоёб… [обход: пробелы между иероглифами]») — в /explain и логе.
#   • плюс то, чего у guard нет для иероглифов: отпечаток текста по знакам (волны одинаковых сообщений) и основы для самообучения.
#
# Как подключить: с guard.py 6.0+ ничего делать не нужно — guard.py сам подхватывает этот файл (GUARD_LANGS, GUARD_ZH=0 — выключить).
# Старые способы (на случай отдельной сборки guard.py):
#   А) запуск вместо guard.py:         python guard_zh.py                (то же, что python guard.py, но с китайским)
#   Б) строка в guard.py ПЕРЕД «if __name__ == "__main__":»:        import guard_zh; guard_zh.install()
# Проверка без Telegram:    python guard_zh.py --zh-selftest      |      python guard_zh.py --zh-check "加V领彩金 日结500"
#
# Настройки .env:  GUARD_ZH=0 — выключить;  GUARD_ZH_STRICT=1 — шире (медицинские слова, «你妈» где угодно и т.п.);
#   GUARD_ZH_KEEP_FOREIGN=auto|1|0 — общий штраф guard «много иероглифов» (+1.5): auto (по умолчанию) — только если есть контакт/ссылка/две группы
#     рекламы, 1 — как раньше всегда, 0 — никогда (китайскоязычный чат);
#   GUARD_ZH_XSLURS=0 — не ловить антикитайские ярлыки (chink / китаёза) латиницей и кириллицей;  GUARD_ZH_LOG=1 — подробный лог.
from __future__ import annotations

