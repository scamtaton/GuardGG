def selftest(verbose: bool = False) -> int:
    bad: list = []
    stats: dict = {}

    def check(group: str, ok: bool, text: str, why: str = "") -> None:
        s = stats.setdefault(group, [0, 0])
        s[1] += 1
        if ok:
            s[0] += 1
        else:
            bad.append((group, text, why))

    for t in CATCH_PROF:
        r = analyze(t)
        check("мат ловится", bool(r and r.found["prof"]), t)
    for t in CATCH_HATE:
        r = analyze(t)
        check("ненависть ловится", bool(r and r.found["hate"]), t)
    for t in CATCH_ADULT:
        r = analyze(t)
        check("18+ ловится", bool(r and r.found["adult"]), t)
    for t in CATCH_MINOR:
        r = analyze(t)
        check("18+ рядом с детьми", bool(r and r.found["adult"] and r.found["minor"]), t)
    for t in CATCH_SPAM:
        r = analyze(t)
        check("реклама/мошенничество (≥4.0)", bool(r and r.spam_raw >= 4.0), t, f"{r.spam_raw if r else None} {[(n, w) for n, w, _ in r.signals] if r else ''}")
    for t in KEEP_CLEAN:
        r = analyze(t)
        dirty = bool(r and (r.found["prof"] or r.found["hate"] or r.found["adult"] or r.spam_raw >= 2.5))
        check("обычная речь не трогается", not dirty, t, str((r.found, r.spam_raw)) if r else "")
    for t in META_OK:
        r = analyze(t)
        check("разговор о слове не наказывается", bool(r and not r.found["prof"] and not r.found["hate"]), t)
    print(f"guard_zh {ZH_VERSION}: самотест" + (" (строгий режим)" if ZH_STRICT else ""))
    total_ok = total = 0
    for g, (ok, n) in stats.items():
        print(f"  {'✓' if ok == n else '✗'} {g}: {ok}/{n}")
        total_ok += ok
        total += n
    for g, t, why in bad:
        print(f"    ПРОМАХ [{g}]: {t!r} {why}")
    print(f"итого: {total_ok}/{total}")
    return 0 if not bad else 1


